import fs from 'node:fs';
import { launch, openIn, stateFileAt, EXAMPLE, modelOf, untilDrawn, pickBox, fieldIn, steps, tick, log, showSide, byTestId } from './lib.mjs';
const VIEW = modelOf(EXAMPLE).views[0];
const browser = await launch();
const o = await openIn(browser, stateFileAt(EXAMPLE));
const { page } = o;
await untilDrawn(page, VIEW);
await showSide(page, 'Details');
await pickBox(page, VIEW, 'Host');
await fieldIn(page, 'name').click(); await page.keyboard.press('End'); await page.keyboard.type('X'); await tick(page);
let dl = null; page.waitForEvent('download', { timeout: 5000 }).then((d) => { dl = d; }, () => {});
await page.keyboard.press('Control+s');
for (let i = 0; i < 100 && !dl; i++) await tick(page);
const saved = JSON.parse(fs.readFileSync(await dl.path(), 'utf8'));
log('saved', { name: saved.model.elements.find((e) => e.id === 'Host').name, lastLog: saved.changes.slice(-2) });
log('bar after save', await page.locator(byTestId('file-name')).textContent(), await steps(page));
await page.keyboard.press('Tab'); await tick(page, 3);
log('bar after Tab', await page.locator(byTestId('file-name')).textContent(), await steps(page), await page.evaluate(() => window.Grasp.session.history.changes.slice(-1)));
await browser.close();
