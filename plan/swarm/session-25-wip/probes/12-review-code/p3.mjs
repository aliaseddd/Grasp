import fs from 'node:fs';
import { launch, openPage, openStateFile, stateFileAt, stateFileOf, modelOf, EXAMPLE, showSide, untilDrawn, readV, frame, selectBox, fieldIn, byTestId, V } from './h.mjs';
const b = await launch();
const view = modelOf(EXAMPLE).views[0];
const o = await openPage(b, { picker: false });
const { page } = o;
await page.setViewportSize({ width: 800, height: 600 });
await showSide(page, 'Validation');
console.log('nofile', JSON.stringify(await readV(page)));
await openStateFile(page, stateFileOf('mixed.json', JSON.parse(fs.readFileSync('mixed.json', 'utf8'))));
await untilDrawn(page, view);
await frame(page);
const r = await readV(page);
console.log('mixed', r.stale, JSON.stringify(r.lists.map(l => l.entries.length)));
await page.screenshot({ path: 'v800.png' });
// overflow check
console.log(await page.evaluate((v) => { const el = document.querySelector(v); const sc = el.closest('.dv-content-container') || el.parentElement; return { w: el.getBoundingClientRect().width, h: el.getBoundingClientRect().height, sw: el.scrollWidth, cw: el.clientWidth, sh: el.scrollHeight, ch: el.clientHeight, docW: document.documentElement.scrollWidth, overflowY: getComputedStyle(el).overflowY, parents: (() => { const out = []; let p = el; while (p && out.length < 6) { out.push([p.className?.toString().slice(0, 40), getComputedStyle(p).overflowY, p.clientHeight, p.scrollHeight]); p = p.parentElement; } return out; })() }; }, V));
// change the file, then ask for another: cancel, then open another
await selectBox(page, view, 'App');
await fieldIn(page, 'name').fill('Host');
await page.waitForTimeout(1000);
console.log('changed', JSON.stringify((await readV(page)).lists.map(l => l.entries.map(e => e[0]))));
await page.locator(byTestId('open')).click();
await frame(page);
console.log('dialog', await page.locator('[role="dialog"]').count(), await page.locator('[role="dialog"]').innerText().catch(() => ''));
await page.getByRole('button', { name: 'Cancel' }).click();
await frame(page);
console.log('after cancel', JSON.stringify((await readV(page)).lists.map(l => l.entries.map(e => e[0]))));
let chooser = null; page.waitForEvent('filechooser').then(c => { chooser = c; });
await page.locator(byTestId('open')).click();
await page.getByRole('button', { name: 'Open another' }).click();
for (let i = 0; i < 50 && !chooser; i++) await frame(page);
await chooser.setFiles({ name: 'stronghold-proof.json', mimeType: 'application/json', buffer: fs.readFileSync(EXAMPLE) });
await page.waitForFunction(() => document.querySelector('[data-testid="file-name"]').textContent === 'stronghold-proof.json');
await frame(page);
const r2 = await readV(page);
console.log('after second', r2.stale, JSON.stringify(r2.lists.map(l => l.entries.map(e => e[0]))));
console.log('problems', o.problems);
await b.close();
