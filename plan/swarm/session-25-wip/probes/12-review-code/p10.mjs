import { launch, openIn, stateFileAt, EXAMPLE, modelOf, untilDrawn, selectBox, fieldIn, byTestId, stubGitHub, frame } from './h.mjs';
const b = await launch();
const view = modelOf(EXAMPLE).views[0];
const o = await openIn(b, stateFileAt(EXAMPLE));
const { page } = o;
await stubGitHub(o.context);
await untilDrawn(page, view);
await selectBox(page, view, 'App');
await fieldIn(page, 'name').fill('Apx');
await page.locator('body').click({ position: { x: 700, y: 500 } }).catch(() => {});
await frame(page);
const name = () => page.locator(byTestId('file-name')).textContent();
console.log('before', await name());
let downloads = 0; page.on('download', () => { downloads += 1; });
await page.locator(byTestId('about')).click();
await page.waitForSelector('[data-testid="about-panel"]');
await page.keyboard.press('Control+z'); await frame(page);
await page.keyboard.press('Control+s'); await page.waitForTimeout(500);
console.log('with About up: name', await name(), 'downloads', downloads, 'box text', await page.evaluate(() => document.querySelector('.react-flow__node[data-id="App"]')?.textContent));
await page.keyboard.press('Escape');
await page.waitForFunction(() => !document.querySelector('[data-testid="about-panel"]'));
await page.waitForTimeout(300);
await page.keyboard.press('Control+z'); await frame(page);
console.log('after close Ctrl+Z: name', await name(), 'box', await page.evaluate(() => document.querySelector('.react-flow__node[data-id="App"]')?.textContent));
// reload while up, unsaved
await page.keyboard.press('Control+y'); await frame(page);
await page.locator(byTestId('about')).click();
await page.waitForSelector('[data-testid="about-panel"]');
await page.reload();
await page.waitForSelector(byTestId('app'));
console.log('dialogs', o.dialogs, 'problems', o.problems);
await b.close();
