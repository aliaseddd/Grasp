import { launch, openIn, stateFileAt, EXAMPLE, modelOf, showSide, untilDrawn, selectBox, fieldIn, readV, frame, byTestId } from './h.mjs';
const b = await launch();
const view = modelOf(EXAMPLE).views[0];
const o = await openIn(b, stateFileAt(EXAMPLE));
const { page } = o;
await showSide(page, 'Validation');
await untilDrawn(page, view);
await selectBox(page, view, 'App');
const f = fieldIn(page, 'name');
await f.fill('Host');
const st = async (w) => { const r = await readV(page); console.log(w, r.stale, JSON.stringify(r.lists.map(l => l.entries.map(e => e[0] + (e[2] ? '*' : ''))))); };
await st('typed, at once');
await page.locator(byTestId('undo')).click(); await frame(page); await st('Undo button right after typing');
await page.locator(byTestId('redo')).click(); await frame(page); await st('Redo button');
await page.waitForTimeout(900); await st('0.9 s after redo');
await page.locator('.react-flow__pane').click({ position: { x: 5, y: 5 } }); await frame(page);
await page.keyboard.press('Control+z'); await frame(page); await st('Ctrl+Z from plane');
await page.keyboard.press('Control+y'); await frame(page); await st('Ctrl+Y from plane');
// focus a validation entry and press Ctrl+Z
await page.locator('[data-testid="validation"] [data-entry="el:App"]').focus();
await page.keyboard.press('Control+z'); await frame(page); await st('Ctrl+Z with an entry focused');
console.log('focus now', await page.evaluate(() => document.activeElement?.tagName + ' ' + (document.activeElement?.dataset?.entry ?? '') + ' ' + document.activeElement?.className.slice(0,30)));
await page.keyboard.press('Control+y'); await frame(page); await st('Ctrl+Y after');
console.log('focus now', await page.evaluate(() => document.activeElement?.tagName + ' ' + (document.activeElement?.dataset?.entry ?? '')));
console.log('problems', o.problems);
await b.close();
