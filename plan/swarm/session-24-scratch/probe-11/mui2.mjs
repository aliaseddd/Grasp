import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
page.on('console', (m) => console.log('console', m.type(), m.text()));
await page.goto(pathToFileURL(path.resolve('mui.html')).href);
await page.waitForSelector('[data-testid="tool"]');
const q = (f, a) => page.evaluate(f, a);
await page.evaluate(() => { window.__cm = []; window.addEventListener('contextmenu', (e) => { window.__cm.push(e.defaultPrevented); }); });
await page.mouse.click(700, 400, { button: 'right' }); await page.waitForSelector('[data-testid="palette"]');
await page.mouse.click(200, 700, { button: 'right' }); await page.waitForTimeout(100);
console.log('right-click outside', await q(() => ({ open: !!document.querySelector('[data-testid="palette"]'), closed: window.__closed, cm: window.__cm, active: document.activeElement.tagName })));
await page.mouse.click(700, 400, { button: 'right' }); await page.waitForSelector('[data-testid="palette"]');
await page.mouse.click(720, 420, { button: 'right' }); await page.waitForTimeout(100);
console.log('right-click on the menu itself', await q(() => ({ open: !!document.querySelector('[data-testid="palette"]'), closed: window.__closed, cm: window.__cm })));
await page.mouse.click(700, 400, { button: 'right' }); await page.waitForSelector('[data-testid="palette"]');
await page.keyboard.press('Escape'); await page.waitForTimeout(50);
console.log('escape', await q(() => ({ open: !!document.querySelector('[data-testid="palette"]'), closed: window.__closed })));
await page.mouse.click(700, 400, { button: 'right' }); await page.waitForSelector('[data-testid="palette"]');
await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await page.waitForTimeout(50);
console.log('arrow+enter', await q(() => ({ open: !!document.querySelector('[data-testid="palette"]'), active: document.activeElement.textContent })));
await page.keyboard.press('Escape');
await page.waitForTimeout(50);
await page.mouse.click(700, 400, { button: 'right' }); await page.waitForSelector('[data-testid="palette"]');
await page.keyboard.press('Tab'); await page.waitForTimeout(50);
console.log('tab', await q(() => ({ open: !!document.querySelector('[data-testid="palette"]'), closed: window.__closed.slice(-1) })));
await browser.close();
