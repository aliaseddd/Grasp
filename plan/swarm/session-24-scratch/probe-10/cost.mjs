import { loadCore, lib } from '../wt-10/canvas/app/test/core.mjs';
import { scaleState, middleService, VIEWS } from '../wt-10/canvas/test/scale-model.mjs';
const core = await loadCore();
const state = scaleState(5000);
const session = core.openSession(lib, JSON.parse(JSON.stringify(state)), { name: 'scale.json' });
const model = session.model;
const id = middleService(5000);
const el = model.elements.find((e) => e.id === id);
console.log('el', el.kind, el.name, 'defs', model.elements.filter((e) => e.kind === el.kind).length, 'rels', model.relationships.length);
const time = (name, fn, n = 200) => { fn(); const t = performance.now(); let r; for (let i = 0; i < n; i++) r = fn(); console.log(name.padEnd(50), ((performance.now() - t) / n).toFixed(3), 'ms'); return r; };
time('detailsOf (no reading)', () => lib.detailsOf(model, 'el', el));
time('detailsOf (in a reading)', () => lib.reading(model, () => lib.detailsOf(model, 'el', el)));
time('describe (no reading)', () => lib.describe(model, el));
time('describe (in a reading)', () => lib.reading(model, () => lib.describe(model, el)));
time('generals (no reading)', () => lib.generals(model, el), 20);
time('generals (in a reading)', () => lib.reading(model, () => lib.generals(model, el)), 20);
const usage = model.elements.find((e) => lib.KINDS[e.kind].definedBy && e.kind === 'PartUsage');
console.log('usage', usage.id, usage.kind);
time('type options (no reading)', () => lib.FIELDS.type.options(model, usage), 20);
time('type options (reading)', () => lib.reading(model, () => lib.FIELDS.type.options(model, usage)), 20);
time('type options + labels (reading)', () => lib.reading(model, () => lib.FIELDS.type.options(model, usage).map((e) => ({ id: e.id, label: lib.textName(e) || '(unnamed)' }))), 20);
time('detailsOf usage (reading)', () => lib.reading(model, () => lib.detailsOf(model, 'el', usage)));
time('firstGeneral (no reading)', () => lib.firstGeneral(model, el));
time('typingOf (no reading)', () => lib.typingOf(model, usage));
const view = model.views[0];
time('detailsOf view (reading)', () => lib.reading(model, () => lib.detailsOf(model, 'view', view)));
const state1 = model.elements.find((e) => e.kind === 'StateUsage' || e.kind === 'StateDefinition');
console.log('state?', !!state1);
time('parallel lock (reading)', () => lib.reading(model, () => { const ids = lib.idsOf(model); return lib.linesOfKind(model, 'TransitionUsage').some((r) => lib.RELATIONSHIPS.TransitionUsage.owner(model, r, ids) === el.id); }));
// a keystroke: edit + describe
let n = 0;
time('edit name (keyed) with said=describe', () => session.history.edit(() => { el.name = 'Service' + (n++); return 'Renamed to ' + lib.describe(model, el); }, 'name:' + el.id), 50);
session.history.endEdit();
console.log(JSON.stringify(lib.detailsOf(model, 'el', el), null, 0).slice(0, 1500));
