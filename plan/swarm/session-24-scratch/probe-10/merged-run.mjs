import { merged } from './merged.mjs';
import { lib, launch, openIn, stateFileOf, finish, viewTab } from '../wt-10/canvas/app/test/helpers.mjs';
const raw = merged();
const m = JSON.parse(JSON.stringify(lib.normalize(raw)));
console.log('elements', m.elements.length, 'rels', m.relationships.length, 'views', m.views.map((v) => `${v.id}:${v.kind}:${Object.keys(v.layout).length}`).join(' '));
const first = {};
for (const e of m.elements) first[e.kind] ??= e.id;
console.log(first);
const firstRel = {};
for (const r of m.relationships) firstRel[r.kind] ??= r.id;
console.log(firstRel);
const browser = await launch();
const opened = await openIn(browser, stateFileOf('fields.json', { model: raw, notes: [], archive: [] }));
for (const v of m.views) await viewTab(opened.page, v);
console.log('problems', opened.problems);
await finish(opened);
await browser.close();
