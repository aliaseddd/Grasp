import { launch, openIn, stateFileAt, TEN, modelOf, showView, linesOf, byTestId, TESTIDS, boxOf, headerOf, frame, finish, groundPoint, viewTab } from '../wt-10/canvas/app/test/helpers.mjs';
const browser = await launch();
const file = TEN.find((f) => f.endsWith('interconnection.json'));
const opened = await openIn(browser, stateFileAt(file));
const { page } = opened;
const model = modelOf(file);
const view = model.views[0];
await showView(page, view);
await page.evaluate(() => {
  const input = document.createElement('input'); input.id = 'probe'; input.style.cssText = 'position:fixed;right:40px;top:80px;z-index:99999';
  document.querySelector('[data-testid="details"]').appendChild(input);
  window.blurs = 0; input.addEventListener('blur', () => { window.blurs += 1; });
});
const state = async (what) => console.log(what, await page.evaluate(() => [window.blurs, document.activeElement.id || document.activeElement.tagName + '.' + document.activeElement.className.slice(0, 40)]));
const focus = () => page.locator('#probe').focus();
await focus(); await state('focused');
const id = Object.keys(view.layout)[0];
const box = await boxOf(page, view.id, id); const at = headerOf(box);
await page.mouse.click(at.x, at.y); await state('after click on node ' + id);
await focus();
const g = await groundPoint(page, view); await page.mouse.click(g.x, g.y); await state('after click on ground');
await focus();
const tab = await viewTab(page, model.views[1]); await tab.click(); await state('after click on a view tab');
await focus();
await page.getByRole('tab', { name: 'Tools', exact: true }).click(); await state('after click on Tools strip tab');
await focus();
await page.locator(byTestId(TESTIDS.undo)).click({ force: true }).catch((e) => console.log('undo click', e.message.slice(0, 60))); await state('after click on disabled undo');
await focus();
await page.locator(byTestId(TESTIDS.open)).hover(); await state('after hover open');
await focus();
await page.locator('.grasp-side-title').first().click(); await state('after click on a side title');
await finish(opened).catch((e) => console.log(e.message.slice(0, 200)));
await browser.close();
