import path from 'node:path';
const H = await import('./wt/canvas/app/test/helpers.mjs');
const { launch, openIn, stateFileAt, stateFileOf, modelOf, showView, frame, viewTab, rowIn, rowItemIn, FIXTURES } = H;
const { scaleState } = await import('./wt/canvas/test/scale-model.mjs');
const browser = await launch();
const out = (label, v) => console.log(label, JSON.stringify(v));
const sel = (page) => page.evaluate(() => ({ items: window.Grasp.selection.items.map((i) => i.type + ':' + i.id), view: window.Grasp.selection.view }));
const marks = (page) => page.evaluate(() => [...document.querySelectorAll('[data-testid="explorer"] [role="treeitem"]')].map((li) => [li.querySelector(':scope > [data-row]').getAttribute('data-row'), li.getAttribute('aria-selected'), li.getAttribute('aria-checked'), li.getAttribute('aria-current'), li.getAttribute('aria-expanded')]).filter((r) => r[1] !== 'false' || r[3]));
const focus = (page) => page.evaluate(() => { const a = document.activeElement; return a ? a.tagName + ':' + (a.querySelector(':scope > [data-row]')?.getAttribute('data-row') ?? '') : null; });
try {
  const IC = path.join(FIXTURES, 'interconnection.json');
  const o = await openIn(browser, stateFileAt(IC));
  const { page } = o;
  const [one, two] = modelOf(IC).views;
  await showView(page, one);
  out('marks at start', await marks(page));
  await rowIn(page, 'el', 'Pump').click(); await frame(page);
  out('click Pump row', await marks(page));
  await (await viewTab(page, two)).click(); await frame(page); await frame(page);
  out('tab two clicked', await marks(page));
  await rowIn(page, 'view', one.id).click(); await frame(page); await frame(page);
  out('click view row one', [await marks(page), await sel(page), await focus(page)]);
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await frame(page); await frame(page);
  out('down, Enter on view row two', [await marks(page), await sel(page), await focus(page), await (await viewTab(page, two)).getAttribute('aria-selected')]);
  await page.keyboard.press('ArrowUp'); await page.keyboard.press('Space'); await frame(page); await frame(page);
  out('up, Space on view row one', [await marks(page), await sel(page), await (await viewTab(page, one)).getAttribute('aria-selected')]);
  console.log('problems', o.problems);
  await o.context.close();
  const o3 = await openIn(browser, stateFileOf('scale-5000.json', scaleState(5000)));
  await frame(o3.page);
  const more = rowIn(o3.page, 'more', 'package:');
  out('more row', [await more.textContent(), await rowItemIn(o3.page, 'more', 'package:').getAttribute('aria-selected')]);
  await more.click(); await frame(o3.page);
  out('after click', [await more.textContent(), await o3.page.evaluate(() => document.querySelectorAll('[data-testid="explorer"] [data-row]').length), await focus(o3.page)]);
  await o3.page.keyboard.press('Enter'); await frame(o3.page);
  out('after Enter on more', [await more.textContent(), await o3.page.evaluate(() => document.querySelectorAll('[data-testid="explorer"] [data-row]').length), await focus(o3.page), await sel(o3.page)]);
  console.log('problems', o3.problems);
  await o3.context.close();
} finally { await browser.close(); }
