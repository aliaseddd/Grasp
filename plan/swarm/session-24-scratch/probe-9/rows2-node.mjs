const ex = planes.openText(lib, fs.readFileSync('./wt/canvas/examples/stronghold-proof.json', 'utf8'), { name: 'ex' });
const st = planes.viewStoreOf(ex, 'v-proof'); st.subscribe(() => {}); st.camera(736, 828);
const rects = planes.project(lib, ex.model, ex.model.views[0], { far: false }).rects;
const around = ['Page.hosts', 'Page.hosts.api', 'Host', 'Host.api'].map((id) => rects.get(id));
const R = { x: Math.min(...around.map((r) => r.x)) - 1, y: Math.min(...around.map((r) => r.y)) - 1 };
R.width = Math.max(...around.map((r) => r.x + r.w)) + 1 - R.x; R.height = Math.max(...around.map((r) => r.y + r.h)) + 1 - R.y;
st.marquee(R);
const sx = planes.selectionOf(ex);
console.log('V6', sx.items.map((i) => i.type + ':' + i.id));
const h = rects.get('Host'); st.marquee({ x: h.x, y: h.y, width: h.w, height: h.h }); console.log('exact Host', sx.items.map((i) => i.type + ':' + i.id));
st.marquee({ x: h.x, y: h.y, width: h.w - 1, height: h.h }); console.log('Host less 1', sx.items.map((i) => i.type + ':' + i.id));
