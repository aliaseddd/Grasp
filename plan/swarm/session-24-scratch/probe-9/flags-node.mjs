const core = await import('./wt/canvas/app/test/core.mjs');
const { scaleState } = await import('./wt/canvas/test/scale-model.mjs');
const m = await core.loadPlanes();
const lib = (await import('./wt/canvas/export.mjs')).loadLib();
const s = m.openText(lib, JSON.stringify(scaleState(5000)), { name: 'big.json' });
const store = m.viewStoreOf(s, 'v-definitions');
store.camera(736, 828);
const stop = store.subscribe(() => {});
const snap = store.getSnapshot();
console.log('nodes', snap.nodes.length, 'edges', snap.edges.length);
const sel = m.selectionOf(s);
const ids = snap.nodes.map((n) => n.id);
let t = performance.now();
for (let i = 0; i < 200; i++) sel.set([{ type: 'el', id: ids[i] }]);
console.log('selection.set with one live store (flags over the view): ms each', ((performance.now() - t) / 200).toFixed(3));
t = performance.now();
for (let i = 0; i < 20000; i++) sel.has('el', ids[i % ids.length]);
console.log('has: ns each', (((performance.now() - t) / 20000) * 1e6).toFixed(0));
t = performance.now(); sel.set(ids.map((id) => ({ type: 'el', id }))); console.log('set 1544 items ms', (performance.now() - t).toFixed(2));
t = performance.now(); store.marquee({ x: -1e6, y: -1e6, width: 2e6, height: 2e6 }); console.log('marquee over everything ms', (performance.now() - t).toFixed(2), sel.items.length);
t = performance.now(); store.marquee({ x: -1e6, y: -1e6, width: 2e6, height: 2e6 }); console.log('same marquee again ms', (performance.now() - t).toFixed(2));
t = performance.now(); store.marquee({ x: 0, y: 0, width: 1, height: 1 }); console.log('marquee over nothing ms', (performance.now() - t).toFixed(2), sel.items.map((i) => i.type + ':' + i.id));
