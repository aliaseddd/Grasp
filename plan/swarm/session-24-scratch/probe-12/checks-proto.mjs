import assert from 'node:assert/strict';
import fs from 'node:fs';
import { loadWith, lib, EXAMPLE, clock, plain } from './tree/canvas/app/test/core.mjs';
const core = await loadWith('core/checks', 'core/probe');
const waits = [];
const later = (run, ms) => { const w = { run, ms, off: false }; waits.push(w); return () => { w.off = true; }; };
let calls = 0;
const counting = Object.freeze({ ...lib, validate: (m) => { calls += 1; return lib.validate(m); } });
const session = core.openText(counting, fs.readFileSync(EXAMPLE, 'utf8'), { name: 'x.json' }, { now: clock() });
const checks = core.checksOf(session, { later });
assert.equal(core.checksOf(session), checks);
assert.deepEqual(checks.state, { found: null, stale: true });
let told = 0;
const stop = checks.listen(() => { told += 1; });
assert.equal(told, 0); assert.equal(calls, 1);
assert.deepEqual(plain(checks.state), { found: { problems: [], diagnostics: [] }, stale: false });
const first = checks.state.found;
const el = (id) => session.model.elements.find((e) => e.id === id);
session.history.edit(() => { el('App').name = 'Hos'; return 'Renamed'; }, 'name:App');
assert.equal(told, 1); assert.equal(checks.state.stale, true); assert.equal(checks.state.found, first); assert.equal(waits.length, 1); assert.equal(waits[0].ms, 800);
session.history.edit(() => { el('App').name = 'Host'; return 'Renamed'; }, 'name:App');
assert.equal(told, 1); assert.equal(waits.length, 2); assert.equal(waits[0].off, true); assert.equal(waits[1].off, false); assert.equal(calls, 1);
session.history.endEdit();
assert.equal(waits.length, 2, 'end starts no wait'); assert.equal(told, 1);
waits[1].run();
assert.equal(told, 2); assert.equal(calls, 2);
console.log(JSON.stringify(plain(checks.state), null, 1));
session.history.undo();
assert.equal(told, 3); assert.equal(calls, 3); assert.equal(checks.state.stale, false); assert.equal(checks.state.found.problems.length, 0); assert.equal(waits.length, 2);
session.history.redo();
assert.equal(told, 4); assert.equal(checks.state.found.problems.length, 2);
const twins = checks.state.found;
stop();
session.history.undo();
assert.equal(calls, 4); assert.equal(checks.state.stale, true); assert.equal(checks.state.found, twins); assert.equal(told, 4);
checks.listen(() => { told += 1; });
assert.equal(calls, 5); assert.equal(checks.state.found.problems.length, 0); assert.equal(told, 4);
// a result that reads the same is the same object
const empty = checks.state.found;
session.history.edit(() => { el('DevHost').doc = 'x'; return 'Doc'; });
waits.at(-1).run();
assert.equal(checks.state.found, empty); assert.equal(checks.state.stale, false);
// about
const m = session.model;
console.log(JSON.stringify([core.aboutProblem(m, { id: 'Host', message: '' }), core.aboutProblem(m, { id: 's-DevHost', message: '' }), core.aboutProblem(m, { id: 't-hosts-api', message: '' }), core.aboutProblem(m, { id: 'v-proof', message: '' }), core.aboutProblem(m, { id: null, message: '' }), core.aboutProblem(m, { id: 'gone', message: '' }), core.aboutDiagnostic(m, { type: null, id: null }), core.aboutDiagnostic(m, { type: 'el', id: 'Page' })]));
