'use strict';

// Prepares src/shared/, which is generated and not committed (.gitignore), before the SPFx build:
//   1. copies the two files every host compiles, app/src/host/host-services.ts and load-app.ts
//   2. writes app-entry.ts with the name of the app's entry file, read from app/dist/stronghold-app.json
// The entry file's name carries a hash of its contents, so the web part learns it at build time, and a new app is
// always a new file for every browser cache. app/src/host is the one place to edit the shared files.
// Same script as hosts/server/scripts/prepare-shared.js, so the two hosts can't drift apart.

const fs = require('fs');
const path = require('path');

const appDir = path.resolve(__dirname, '..', '..', '..', 'app');
const from = path.join(appDir, 'src', 'host');
const to = path.resolve(__dirname, '..', 'src', 'shared');
const files = ['host-services.ts', 'load-app.ts'];
const buildManifest = path.join(appDir, 'dist', 'stronghold-app.json');

if (!fs.existsSync(buildManifest)) {
  console.error('No app build at ' + buildManifest + '. Run `npm run build` in app/ first.');
  process.exit(1);
}
const entry = JSON.parse(fs.readFileSync(buildManifest, 'utf8')).entry;

// Start from an empty folder, so a file that was renamed or dropped in app/src/host doesn't linger here and get
// compiled anyway.
if (fs.existsSync(to)) {
  for (const name of fs.readdirSync(to)) {
    fs.unlinkSync(path.join(to, name));
  }
} else {
  fs.mkdirSync(to);
}
for (const file of files) {
  const banner = '// GENERATED by scripts/prepare-shared.js from app/src/host/' + file + '. Edit the original, not this copy.\n\n';
  fs.writeFileSync(path.join(to, file), banner + fs.readFileSync(path.join(from, file), 'utf8'));
}
fs.writeFileSync(path.join(to, 'app-entry.ts'),
  '// GENERATED by scripts/prepare-shared.js from app/dist/stronghold-app.json. Rebuild the app to change it.\n\n' +
  "/** The app's entry file in this package. Its name carries a hash of its contents. */\n" +
  "export const APP_ENTRY_FILE: string = '" + entry + "';\n"); // single quotes: SPFx 1.4.1's quotemark rule
console.log('Prepared ' + to + ': ' + files.join(', ') + ', app-entry.ts (' + entry + ')');
